#!/usr/bin/env python3
"""LaTeX fragments for the SI tables: excluded questions, refusal patterns, EM and ROUGE-L.

S2 comes from data/results-campaign/exclusions.json (controlled grid;
gpt-5-mini and claude-sonnet-5-5 entries) and exclusions_f23.json (the Sonnet
budget-matched cells; kept apart so the grid n is unchanged), dataset,
question id and category only, in two blocks. S3 is
REFUSAL_PATTERNS of experiments/analysis/refusal_analysis.py,
verbatim and in order. The EM and ROUGE-L table reads
scripts/paper/out/controlled_grid_em_rouge.csv, written by
controlled_grid_em_rouge.py (run that first). Writes si_table_exclusions.tex,
si_table_refusal_patterns.tex and si_table_em_rouge.tex to
scripts/paper/out/si/. Captions are one short sentence. Definitions go in
a note under the table. Reads only.

    uv run python scripts/paper/si_tables.py
"""

import argparse
import csv
import json
import subprocess
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ap = argparse.ArgumentParser()
REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "scripts" / "paper" / "out"
ap.add_argument("--code-repo", type=Path, default=REPO)
ap.add_argument("--out", type=Path, default=OUT / "si")
ap.add_argument("--em-rouge", type=Path, default=OUT / "controlled_grid_em_rouge.csv")
args = ap.parse_args()
code = args.code_repo.resolve()
sys.path.insert(0, str(code))
head = subprocess.run(
    ["git", "-C", str(code), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
).stdout.strip()

from experiments.analysis.refusal_analysis import REFUSAL_PATTERNS  # noqa: E402

out_dir = args.out
out_dir.mkdir(parents=True, exist_ok=True)
ESC = {
    "\\": r"\textbackslash{}",
    "{": r"\{",
    "}": r"\}",
    "_": r"\_",
    "%": r"\%",
    "&": r"\&",
    "#": r"\#",
    "$": r"\$",
    "^": r"\^{}",
    "~": r"\~{}",
    "|": r"\textbar{}",
    "<": r"\textless{}",
    ">": r"\textgreater{}",
}


def tex(s: str, breakable: str = "") -> str:
    """LaTeX-escaped text. breakable="id" adds break points every 8 characters and after an
    underscore (identifiers); breakable="regex" adds them after an alternation bar only."""
    out = []
    for i, c in enumerate(s):
        out.append(ESC.get(c, c))
        if (breakable == "id" and (c == "_" or (i + 1) % 8 == 0)) or (
            breakable == "regex" and c == "|"
        ):
            out.append(r"\allowbreak{}")
    return "".join(out)


def note(text: str) -> list[str]:
    """Table note under the tabular (the main text's tab:cost pattern); the caption stays one short sentence."""
    return [
        "\\par\\smallskip",
        f"\\begin{{minipage}}{{\\linewidth}}\\footnotesize {text}\\end{{minipage}}",
    ]


# ---- Table S2 -------------------------------------------------------------
CATEGORY = {"azure_content_filter": "platform filter", "anthropic_refusal": "refusal stop"}
MODEL = {"gpt-5-mini": "gpt-5-mini", "claude-sonnet-5-5": "Claude Sonnet 5.5"}
WORKLOAD = {
    "hotpotqa": "HotpotQA",
    "2wikimultihopqa": "2WikiMultiHopQA",
    "musique": "MuSiQue",
    "financebench": "FinanceBench",
}
# Row names of tab:budget in the manuscript.
CELL = {
    "budget_matched_loop_(budget=10)": "Loop at ten calls",
    "budget_matched_agentic_(budget=6)": "\\agentic{} at six calls",
}
results = code / "data/results-campaign"


def entries(name: str):
    data = json.loads((results / name).read_text(encoding="utf-8"))
    for model in MODEL:
        for dataset in WORKLOAD:
            yield from ((model, dataset, e) for e in (data.get(dataset) or {}).get(model, []))


grid_rows = [
    (MODEL[m], WORKLOAD[d], CATEGORY[e["reason"]], e["id"])
    for m, d, e in entries("exclusions.json")
]
# One row per (question, cell); a question can be final in several cells.
budget_rows = [
    (MODEL[m], f"{WORKLOAD[d]}, {CELL[e['pipeline']]}", CATEGORY[e["reason"]], e["id"])
    for m, d, e in entries("exclusions_f23.json")
]
rows = grid_rows + budget_rows
lines = [
    "% Table S2. Generated by scripts/paper/si_tables.py from data/results-campaign/exclusions.json and exclusions_f23.json. Do not edit by hand.",
    "\\begin{table}[t]",
    "\\centering",
    "\\caption{Questions removed for a final provider-declined request.}",
    "\\label{tab:si_exclusions}",
    "\\footnotesize",
    "\\begin{tabular}{@{}p{0.14\\textwidth}p{0.27\\textwidth}p{0.13\\textwidth}p{0.3\\textwidth}@{}}",
    "\\toprule",
    "\\textbf{Model} & \\textbf{Workload} & \\textbf{Category} & \\textbf{Question identifier} \\\\",
    "\\midrule",
    "\\multicolumn{4}{@{}l}{\\emph{(a) Controlled grid}} \\\\",
]
prev = None
for model, workload, cat, qid in grid_rows:
    if prev is not None and model != prev:
        lines.append("\\midrule")
    prev = model
    lines.append(f"{model} & {workload} & {cat} & \\texttt{{{tex(qid, breakable='id')}}} \\\\")
lines += ["\\midrule", "\\multicolumn{4}{@{}l}{\\emph{(b) Budget-matched cells}} \\\\"]
for model, workload, cat, qid in budget_rows:
    lines.append(f"{model} & {workload} & {cat} & \\texttt{{{tex(qid, breakable='id')}}} \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
lines += note(
    "\\emph{(a) Controlled grid}: removed from every pipeline and every run of the workload, for the named model. "
    "\\emph{(b) Budget-matched cells}: removed, together with the questions of (a), from the budget-matched comparisons of the named model and workload. "
    "The grid analysis keeps list (a). "
    "\\emph{Platform filter}: the Azure content filter stopped the request as a final error. "
    "\\emph{Refusal stop}: the Anthropic API returned the refusal stop reason, category \\texttt{reasoning\\_extraction}, after the third resend."
)
lines += ["\\end{table}", ""]
(out_dir / "si_table_exclusions.tex").write_text("\n".join(lines), encoding="utf-8")

# ---- Table S3 -------------------------------------------------------------
lines = [
    f"% Table S3. Generated by scripts/paper/si_tables.py from REFUSAL_PATTERNS (code {head}). Do not edit by hand.",
    "\\begin{table}[t]",
    "\\centering",
    "\\caption{Refusal markers matched in answers.}",
    "\\label{tab:si_refusal_patterns}",
    "\\footnotesize",
    "\\begin{tabular}{@{}rp{0.75\\textwidth}@{}}",
    "\\toprule",
    "\\textbf{No.} & \\textbf{Regular expression} \\\\",
    "\\midrule",
]
for i, pat in enumerate(REFUSAL_PATTERNS, 1):
    lines.append(f"{i} & \\texttt{{{tex(pat, breakable='regex')}}} \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
lines += note(
    f"The {len(REFUSAL_PATTERNS)} regular expressions mark a prediction as a refusal. A prediction is counted as a refusal when at least one of them "
    "matches anywhere in the raw prediction text, ignoring case."
)
lines += ["\\end{table}", ""]
(out_dir / "si_table_refusal_patterns.tex").write_text("\n".join(lines), encoding="utf-8")
# ---- EM and ROUGE-L per cell -------------------------------------------
CONFIG = {
    "naive_rag": "Naive RAG",
    "single-pass": "Single-Pass",
    "loop_refinement": "Loop Refinement",
    "agentic_(react)": "\\agentic{}",
    "crag_replica": "CRAG-style",
}
COLS = [
    ("hotpotqa", 2),
    ("2wikimultihopqa", 2),
    ("2wikimultihopqa", 4),
    ("musique", 2),
    ("musique", 3),
    ("musique", 4),
    ("financebench", 1),
]  # the cells of tab:rq1_main, in its column order
with open(args.em_rouge, encoding="utf-8") as fh:
    emr = {(r["model"], r["dataset"], int(r["hop"]), r["pipeline"]): r for r in csv.DictReader(fh)}
assert len(emr) == len(MODEL) * len(COLS) * len(CONFIG), len(emr)


def num(x: str) -> str:
    # three decimals, ties away from zero (.0625 -> .063), from the CSV's shortest repr
    v = f"{Decimal(repr(float(x))).quantize(Decimal('0.001'), rounding=ROUND_HALF_UP):.3f}"
    return v[1:] if v.startswith("0") else v


lines = [
    "% EM and ROUGE-L table. Generated by scripts/paper/si_tables.py from scripts/paper/out/controlled_grid_em_rouge.csv "
    "(scripts/paper/controlled_grid_em_rouge.py). Do not edit by hand.",
    "\\begin{table}[t]",
    "\\centering",
    "\\caption{EM and ROUGE-L per cell under control.}",
    "\\label{tab:si_em_rouge}",
    "\\footnotesize",
    "\\setlength{\\tabcolsep}{4pt}",
    "\\begin{tabular}{@{}ll ccccccc@{}}",
    "\\toprule",
    "& & \\textbf{HotpotQA} & \\multicolumn{2}{c}{\\textbf{2WikiMultiHopQA}} & \\multicolumn{3}{c}{\\textbf{MuSiQue}} & \\textbf{FinanceBench} \\\\",
    "\\cmidrule(lr){3-3} \\cmidrule(lr){4-5} \\cmidrule(lr){6-8} \\cmidrule(lr){9-9}",
    "\\textbf{Metric} & \\textbf{Configuration} & 2-hop & 2-hop & 4-hop & 2-hop & 3-hop & 4-hop & 1-hop \\\\",
]
for i, model in enumerate(MODEL):
    lines += ["\\midrule", f"\\multicolumn{{9}}{{@{{}}l}}{{\\emph{{{MODEL[model]}}}}} \\\\"]
    ns = [emr[(model, d, h, "naive_rag")]["n"] for d, h in COLS]
    lines.append("& $n$ & " + " & ".join(ns) + " \\\\")
    for metric, label in (("em", "EM"), ("rouge_l", "ROUGE-L")):
        for j, pipe in enumerate(CONFIG):
            head_cell = label if j == 0 else ""
            lines.append(
                f"{head_cell} & {CONFIG[pipe]} & "
                + " & ".join(num(emr[(model, d, h, pipe)][metric]) for d, h in COLS)
                + " \\\\"
            )
lines += ["\\bottomrule", "\\end{tabular}"]
lines += note(
    "A cell is one model family, one workload and one hop bin, as in Table~\\ref{main-tab:rq1_main}. "
    "Each value is the mean over the questions of the cell of the per-question mean over runs, "
    "with three runs per configuration and one run for CRAG-style. "
    "The questions of Table~\\ref{tab:si_exclusions}(a) are removed. "
    "Exact match (EM) and ROUGE-L take the maximum over the reference variants of a question, as F1 does. "
    "No test is applied to these values."
)
lines += ["\\end{table}", ""]
(out_dir / "si_table_em_rouge.tex").write_text("\n".join(lines), encoding="utf-8")

print(
    f"S2 rows {len(rows)} (grid {len(grid_rows)}, budget-matched {len(budget_rows)}), S3 patterns {len(REFUSAL_PATTERNS)}, EM/ROUGE-L cells {len(emr)}, code {head}"
)
